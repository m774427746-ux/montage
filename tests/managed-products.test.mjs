import assert from 'node:assert/strict';
import {examples,validate,initialCount,barcodeFor,combineCatalog} from '../server/managed-products.js';
assert(initialCount>=30,'Expected practical offset and gift examples');
assert(examples.every(x=>x.price===null),'Demo products cannot have invented prices');
assert(examples.some(x=>x.name.includes('فواتير')));
assert(examples.some(x=>x.name.includes('4 أونص')));
assert(examples.some(x=>x.name.includes('درع')));
assert(examples.every((x,i)=>x.sku===String(i+1).padStart(6,'0')),'SKU must increase for every product');
assert.equal(new Set(examples.map(x=>x.sku)).size,examples.length);
assert.equal(barcodeFor(examples.find(x=>x.category==='offset')),null);
assert.equal(barcodeFor(examples.find(x=>x.category==='gifts')),'GFT'+examples.find(x=>x.category==='gifts').sku);
const p={category:'gifts',name:'هدية تجريبية',spec:'حفر ليزر',unit:'قطعة',notes:'',packQty:100,price:200,active:true,supplierOfferIds:[]};
const result=validate(p);assert(result.id);assert.equal(result.price,200);assert.equal(result.sku,null);
const fixed=validate({...p,name:'هدية جديدة'}, {...result,sku:'000900'});assert.equal(fixed.sku,'000900');assert.equal(fixed.id,result.id);
for(const bad of [{...p,category:'oops'},{...p,price:-2},{...p,packQty:1.2},{...p,active:'true'},{...p,supplierOfferIds:['x','x']}]) assert.throws(()=>validate(bad));
assert.throws(()=>validate({...p,category:'offset'},result),'Cannot reassign SKU to a new category');
const legacy=[{...examples[0],price:55}];
const merged=combineCatalog(legacy,[]);assert.equal(merged.length,examples.length);assert.equal(merged[0].price,55);
const edits=[{...examples[1],price:90}];assert.equal(combineCatalog(legacy,edits)[1].price,90);
console.log('Product identities, supplier linkage validation and demo seed tests passed');